// استيراد من `src` تبع حزمة `pdf` عن قصد: جدول التشكيل العربي مو
// مُصدَّر بواجهتها العامة، وإعادة كتابته عنا معناها نسخة تانية من جدول
// ٤٠ حرف × ٤ أشكال + الروابط — مصدر أخطاء أكبر من الاستيراد نفسه.
//
// الخطر مقبول: إذا الحزمة غيّرت المسار، البناء بيفشل **فوراً** بخطأ
// ترجمة — مو بصمت. والنسخة مثبّتة بـ pubspec.lock.
// و`test/arabic_text_test.dart` بيمسك أي تغيير بسلوكها.
// ignore: implementation_imports
import 'package:pdf/src/pdf/font/arabic.dart' as arabic;

final _arabicRange = RegExp(r'[؀-ۿݐ-ݿﭐ-﷿ﹰ-﻿]');

bool hasArabic(String text) => _arabicRange.hasMatch(text);

/// بيحضّر نصاً عربياً للرسم داخل الـ PDF.
///
/// ملفات PDF ما فيها محرّك تشكيل: كل حرف بينرسم بالشكل يلي منعطيه ياه. فإذا
/// بعتنا الحروف الأساسية متل ما هي، بتطلع منفصلة («ﺍﺱﻡ ﺍﻝ ﻉﻡﻱﻝ») لأن الشكل
/// الأساسي لكل حرف هو الشكل المنفصل.
///
/// حزمة `pdf` فيها [arabic.convert] وهي بتعمل التشكيل **صح**: بتختار الشكل
/// المناسب لكل حرف حسب جيرانه (أولي/وسطي/نهائي) وبترجّع النص بالترتيب
/// البصري. بس بتعكس النص **كله**، فبينقلب ترتيب الكلمات كمان: «اسم العميل»
/// بتصير «العميل اسم».
///
/// عشان هيك منشكّل كل كلمة لحالها وبعدين منعكس ترتيب الكلمات — فمنجمع
/// التشكيل الصحيح مع الترتيب الصحيح.
///
/// الكلمات غير العربية (أرقام، لاتيني، رموز) بتضل متل ما هي — بس محلّها
/// بينعكس مع باقي السطر، لأن السطر ككل بينقرأ من اليمين لليسار.
///
/// **لا تلفّ الناتج بـ `pw.Directionality`.** الحزمة وقتها بتعيد المعالجة
/// فوق معالجتنا وبتكسر التشكيل من جديد.
String shapeForPdf(String text) {
  if (!hasArabic(text)) return text;

  final words = text.split(' ');
  final shaped = [
    for (final word in words)
      if (hasArabic(word)) arabic.convert(word) else word,
  ];
  return shaped.reversed.join(' ');
}
